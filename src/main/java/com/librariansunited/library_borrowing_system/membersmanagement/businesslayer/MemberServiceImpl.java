package com.librariansunited.library_borrowing_system.membersmanagement.businesslayer;

import com.librariansunited.library_borrowing_system.DuplicateMemberEmailException;
import com.librariansunited.library_borrowing_system.EntityNotFoundException;
import com.librariansunited.library_borrowing_system.membersmanagement.domainlayer.Member;
import com.librariansunited.library_borrowing_system.membersmanagement.domainlayer.MemberStatus;
import com.librariansunited.library_borrowing_system.membersmanagement.infrastructurelayer.MemberRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;

import java.util.List;

import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;

import java.time.LocalDate;
import java.util.List;

@Service
@RequiredArgsConstructor
public class MemberServiceImpl implements MemberService {

    private final MemberRepository memberRepository;

    // ------------------------------------------------------------ queries

    @Override
    public List<Member> getAllMembers() {
        return this.memberRepository.findAll();
    }

    @Override
    public Member getMemberById(Integer id)
            throws EntityNotFoundException {

        return this.memberRepository.findById(id)
                .orElseThrow(() -> new EntityNotFoundException(
                        "Member not found with id: " + id));
    }

    @Override
    public List<Member> getMembersByMemberStatus(
            MemberStatus memberStatus) {

        return this.memberRepository.findByMemberStatus(memberStatus);
    }

    // ----------------------------------------------------------- commands

    @Override
    public Member addMember(Member member) {

        validateMember(member);

        // Defensive: the identifier is always generated by the system.
        member.setId(null);

        if (this.memberRepository.existsByEmail(
                member.getEmail())) {
            throw new DuplicateMemberEmailException(
                    member.getEmail().getValue());
        }

        // Fill in the data that the client is not allowed to provide.
        member.setMemberStatus(MemberStatus.ACTIVE);
        member.setActiveLoanCount(0);
        if (member.getRegistrationDate() == null) {
            member.setRegistrationDate(LocalDate.now());
        }

        return this.memberRepository.save(member);
    }

    @Override
    public Member updateMember(Integer id, Member updatedMember)
            throws EntityNotFoundException {

        validateMember(updatedMember);

        Member existingMember = this.getMemberById(id);

        validateDeactivation(existingMember, updatedMember);

        // Preserve the fields that the client cannot change.
        updatedMember.setId(id);
        updatedMember.setMemberStatus(existingMember.getMemberStatus());
        updatedMember.setActiveLoanCount(
                existingMember.getActiveLoanCount());
        updatedMember.setRegistrationDate(
                existingMember.getRegistrationDate());

        return this.memberRepository.save(updatedMember);
    }

    @Override
    public void deleteById(Integer id) throws EntityNotFoundException {

        if (!this.memberRepository.existsById(id)) {
            throw new EntityNotFoundException(
                    "Member not found with id: " + id);
        }

        this.memberRepository.deleteById(id);
    }

    // --------------------------------------------------------- validation

    @Override
    public boolean existsById(Integer id){
        return false;
    }

    private void validateMember(Member member) {

        if (member == null) {
            throw new IllegalArgumentException(
                    "Member cannot be null.");
        }

        if (member.getActiveLoanCount() < 0) {
            throw new IllegalArgumentException(
                    "Active loan count cannot be negative.");
        }

        if (member.getName() == null
                || member.getName().getFirstName() == null
                || member.getName().getFirstName().isBlank()) {
            throw new IllegalArgumentException(
                    "First name is required.");
        }

        if (member.getName().getLastName() == null
                || member.getName().getLastName().isBlank()) {
            throw new IllegalArgumentException(
                    "Last name is required.");
        }

        if (member.getEmail() == null
                || member.getEmail().getValue() == null
                || member.getEmail().getValue().isBlank()) {
            throw new IllegalArgumentException(
                    "Email is required.");
        }

        if (member.getMembershipTier() == null) {
            throw new IllegalArgumentException(
                    "Membership tier is required.");
        }
    }

    private void validateDeactivation(
            Member existingMember,
            Member updatedMember) {

        if (existingMember.getMemberStatus() == MemberStatus.ACTIVE
                &&
                updatedMember.getMemberStatus() == MemberStatus.SUSPENDED
                &&
                existingMember.getActiveLoanCount() > 0) {

            throw new IllegalStateException(
                    "A member with active loans cannot be deactivated.");
        }
    }
}
